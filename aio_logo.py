def aio_logo_png() -> bytes:
    import base64

    return base64.b64decode("".join(AIO_LOGO_PNG_B64.split()))


def aio_logo_ico() -> bytes:
    """Wrap the embedded PNG in an ICO container (Vista+ PNG-in-ICO)."""
    png = aio_logo_png()
    # ICONDIR: reserved, type=1, count=1
    header = (0).to_bytes(2, "little") + (1).to_bytes(2, "little") + (1).to_bytes(2, "little")
    # ICONDIRENTRY: 0,0 means 256; PNG has no AND mask
    entry = bytes([0, 0, 0, 0]) + (1).to_bytes(2, "little") + (32).to_bytes(2, "little")
    entry += (len(png)).to_bytes(4, "little") + (6 + 16).to_bytes(4, "little")
    return header + entry + png


def write_build_icon(path: str | Path) -> Path:
    dest = Path(path)
    dest.write_bytes(aio_logo_ico())
    return dest


def apply_hwnd_icon(hwnd: int) -> None:
    if os.name != "nt":
        return
    import ctypes
    import tempfile

    ico = Path(tempfile.gettempdir()) / "axiox-aio-logo.ico"
    write_build_icon(ico)
    IMAGE_ICON = 1
    LR_LOADFROMFILE = 0x0010
    WM_SETICON = 0x0080
    handle = ctypes.windll.user32.LoadImageW(None, str(ico), IMAGE_ICON, 0, 0, LR_LOADFROMFILE)
    if handle:
        ctypes.windll.user32.SendMessageW(hwnd, WM_SETICON, 0, handle)
        ctypes.windll.user32.SendMessageW(hwnd, WM_SETICON, 1, handle)
